"""rag 包的自定义异常体系。

本模块定义了 rag 包中所有异常的基类和具体异常类型，
用于在多路检索、重排序、Prompt 构建以及端到端编排等 RAG 核心流程中
统一错误处理策略，方便调用方按阶段捕获并区分不同环节的失败。
"""

from __future__ import annotations


class RAGError(Exception):
    """rag 包所有异常的基类。

    所有 rag 包内抛出的异常都应继承自本类，以便调用方可以统一捕获和
    处理 RAG 链路（检索 / 重排序 / Prompt 构建 / 编排）相关的错误。
    本类本身不应被直接实例化，而应通过其具体子类来区分错误发生的阶段。
    """


class RetrievalError(RAGError):
    """检索阶段的错误。

    适用于以下场景：
    - 向量检索失败（例如向量存储不可用、相似度查询超时或返回非法结果）
    - 关键词检索（BM25）失败（例如索引缺失、分词器异常）
    - 混合 / 融合检索（如 RRF 融合）在合并多路结果时失败

    调用方应捕获本异常并向用户报告检索失败的具体原因，
    不应将本异常视为重排序或 Prompt 构建阶段的错误。
    """


class RerankError(RAGError):
    """重排序阶段的错误。

    适用于以下场景：
    - 交叉编码器（CrossEncoder）模型加载失败或不可用
    - 重排序模型推理过程中抛出异常
    - 重排序输入格式非法（例如候选列表为空或结构不符合约定）

    调用方应捕获本异常并向用户报告重排序失败的原因，
    通常发生在检索成功返回候选结果之后、构建最终上下文之前。
    """


class PromptBuildError(RAGError):
    """Prompt 构建阶段的错误。

    适用于以下场景：
    - 引用片段（citation）格式非法或字段缺失
    - 模板渲染失败（例如占位符与上下文变量不匹配）
    - 构造最终 Prompt 时出现截断、超长或编码等异常

    调用方应捕获本异常并向用户报告 Prompt 构建失败的原因，
    通常发生在检索与重排序均成功之后、调用 LLM 之前。
    """


class RAGChainError(RAGError):
    """端到端编排阶段的错误。

    适用于以下场景：
    - RAGChain 将检索、重排序、Prompt 构建、LLM 调用串接成完整链路时失败
    - 编排过程中某一步骤返回非法中间结果或链路状态不一致
    - 链路整体执行超时或被外部中断

    调用方应捕获本异常以感知整条 RAG 链路级别的失败，
    对于可归因到具体阶段的错误，应优先使用上述阶段专属异常。
    """
